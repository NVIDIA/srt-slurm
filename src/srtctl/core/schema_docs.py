def _nested_types(cls: Any) -> list[type]:
    hints = get_type_hints(cls, include_extras=True)
    found: list[type] = []
    for item in fields(cls):
        if _yaml_key(item) is None:
            continue
        for target in _dataclass_targets(hints.get(item.name, item.type)):
            if target not in found:
                found.append(target)
    return found


def _walk(root: type, skip: AbstractSet[type]) -> list[type]:
    """Breadth-first list of dataclasses reachable from ``root`` (root excluded)."""
    order: list[type] = []
    queue = [root]
    seen = {root}
    while queue:
        current = queue.pop(0)
        for nested in _nested_types(current):
            if nested in seen or nested in skip:
                continue
            seen.add(nested)
            order.append(nested)
            queue.append(nested)
    return order


def _render_class_section(cls: type, level: int, *, only_legacy: bool = False) -> list[str]:
    heading = "#" * level
    lines = [f"{heading} {cls.__name__}", ""]
    summary = _class_summary(cls)
    if summary:
        lines.extend([summary, ""])
    lines.extend(_render_table(cls, only_legacy=only_legacy))
    lines.append("")
    return lines


def render_schema_reference() -> str:
    """Render the 2.0 field-level reference for recipes and the cluster config."""
    lines: list[str] = [
        "# Schema Reference",
        "",
        GENERATED_NOTICE,
        "",
        (
            "Field-level reference for the 2.0 recipe layout (`schema: 2`) and the cluster config "
            "`srtslurm.yaml` (`ClusterConfig`), generated from `srtctl.core.roles`, `srtctl.core.placement`, "
            "and the dataclasses in `srtctl.core.schema` and `srtctl.backends`. Each table lists the YAML key, "
            "the type, the default (`required` when there is none), and a description taken from the class "
            "docstring or the comment on the field. Nested types link to their own table. The v1 layout and "
            "the internal fields it maps onto are documented in [legacy-v1.md](legacy-v1.md); for prose, "
            "examples, and semantics see [config-reference.md](config-reference.md)."
        ),
        "",
        "## Recipe",
        "",
        "Top-level keys of a recipe YAML.",
        "",
    ]
    lines.extend(_render_top_level_table())
    lines.append("")
    lines.extend(_render_authoring_surface())

    hidden_classes = LEGACY_CLASSES | INTERNAL_CLASSES
    nested = [cls for cls in _walk(SrtConfig, skip=_BACKEND_CLASSES) if cls not in hidden_classes]
    if nested:
        lines.extend(["## Recipe sections", ""])
        for cls in nested:
            lines.extend(_render_class_section(cls, level=3))

    lines.extend(
        [
            "## Engine types",
            "",
            "`engine.type` selects one of the following; the remaining `engine` keys are that type's knobs.",
            "",
        ]
    )
    engine_nested: list[type] = []
    for type_name, cls in BACKEND_TYPES:
        lines.extend([f"### {cls.__name__}", "", f"`engine.type: {type_name}`", ""])
        summary = _class_summary(cls)
        if summary:
            lines.extend([summary, ""])
        lines.extend(_render_table(cls))
        lines.append("")
        for extra in _walk(cls, skip=_BACKEND_CLASSES | set(nested)):
            if extra not in engine_nested and extra not in hidden_classes:
                engine_nested.append(extra)
    for cls in engine_nested:
        lines.extend(_render_class_section(cls, level=3))

    lines.extend(
        [
            "## Cluster config",
            "",
            "Top-level keys of `srtslurm.yaml`. Recipes inherit these defaults and resolve aliases through them.",
            "",
        ]
    )
    lines.extend(_render_table(ClusterConfig))
    lines.append("")
    for cls in _walk(ClusterConfig, skip=_BACKEND_CLASSES | set(nested) | set(engine_nested)):
        lines.extend(_render_class_section(cls, level=3))

    return "\n".join(lines).rstrip() + "\n"


