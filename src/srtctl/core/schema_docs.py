"""Generate ``docs/schema-reference.md`` from the code.

The recipe schema is the dataclass tree rooted at :class:`SrtConfig`; the
cluster config (``srtslurm.yaml``) is :class:`ClusterConfig`. This module walks
both and renders one Markdown table per dataclass, so the field-level reference
cannot drift from the code: the checked-in file is regenerated by
``srtctl schema-docs`` and CI fails when it is stale.

The document describes the authoring surface only: every dataclass field a
recipe may set, rooted at ``engine:``, ``roles:`` and the ``placement:`` blocks.
The engine dataclasses carry the recipe's ``roles`` (bound at load) and the
Mooncake master block (filled from ``services:``); a recipe writes neither on
``engine``, so :data:`INTERNAL_FIELDS` leaves them out. The pre-2.0 layout is
documented, for migration only, in the hand-written ``docs/legacy-v1.md``.

Descriptions come from three places, in priority order: an ``Attributes:`` block
in the class docstring (Google style), a string literal directly below a field,
then the ``#`` comment block directly above a field or the trailing comment on
its line. Every authoring field must have one; ``tests/test_schema_docs.py``
fails on a field without a description.

The same walk backs :func:`json_schema` (``srtctl schema``) and the MCP
``explain_field`` tool, so the Markdown tables, the JSON Schema, and the agent
tooling read one source.
"""

