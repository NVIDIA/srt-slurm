def _role_legacy_fields() -> dict[str, str]:
    """``resources.<role>_nodes`` and friends -> their ``roles.<role>.*`` spelling."""
    out: dict[str, str] = {}
    for role in ROLE_NAMES:
        out[f"{role}_nodes"] = f"`roles.{role}.nodes`" + (
            f" (`{COLOCATE}` replaces the `0` sentinel)" if role == "decode" else ""
        )
        out[f"{role}_workers"] = f"`roles.{role}.workers`"
        out[f"gpus_per_{role}"] = f"`roles.{role}.gpus`"
    return out


def _backend_legacy_fields(engine_key: str) -> dict[str, str]:
    """Per-mode ``backend`` fields -> their ``roles.<role>.*`` spelling, for one engine's config key."""
    out: dict[str, str] = {}
    for role in ROLE_NAMES:
        mode = ROLE_TO_MODE[role]
        out[f"{mode}_environment"] = f"`roles.{role}.env`"
        out[f"{mode}_extra_args"] = f"`roles.{role}.extra_args`"
    out[engine_key] = "`roles.<role>.args` (one mapping per role; the `prefill` / `decode` / `aggregated` keys)"
    out["kv_events_config"] = "`roles.<role>.kv_events`"
    out["mooncake_kv_store"] = (
        "a `services:` entry of type `mooncake-master` plus the worker env on `roles.<role>.env` "
        "(see [mooncake-kv-store.md](mooncake-kv-store.md))"
    )
    return out


def _present(cls: type, mapping: dict[str, str]) -> dict[str, str]:
    """Keep only the keys ``cls`` actually declares (TRT-LLM alone has ``*_extra_args``)."""
    keys = {row.key for row in field_docs(cls)}
    return {key: value for key, value in mapping.items() if key in keys}


