def _row(row: FieldDoc) -> str:
    return f"| `{row.key}` | {row.type_label} | {row.default} | {_cell(row.description)} |"


def _table_header() -> list[str]:
    return ["| Key | Type | Default | Description |", "|---|---|---|---|"]


def _legacy_keys(cls: type) -> set[str]:
    return set(LEGACY_FIELDS.get(cls, {}))


def _render_table(cls: type, *, only_legacy: bool = False) -> list[str]:
    """Field table for ``cls``: the 2.0 rows by default, or only the v1 rows."""
    legacy = _legacy_keys(cls)
    out = _table_header()
    for row in field_docs(cls):
        if row.key in _V2_SERVICE_OPTION_FIELDS.get(cls, ()) or row.key in INTERNAL_FIELDS.get(cls, {}):
            continue
        if (row.key in legacy) == only_legacy:
            out.append(_row(row))
    return out


def _render_top_level_table() -> list[str]:
    """The recipe's top-level keys in the 2.0 layout: dataclass fields minus v1 keys, plus engine/roles."""
    out = _table_header()
    for row in field_docs(SrtConfig):
        if row.key in LEGACY_TOP_LEVEL:
            continue
        if row.key == "schema":
            row = FieldDoc(row.key, row.type_label, "`2`", "Recipe schema version. Write `schema: 2` for this layout.")
        out.append(_row(row))
        if row.key == "resources":
            out.extend(_row(v2) for v2 in _V2_TOP_LEVEL_ROWS)
    return out


