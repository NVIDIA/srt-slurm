"""Generate ``docs/schema-reference.md`` and ``docs/legacy-v1.md`` from the code.

The recipe schema is the dataclass tree rooted at :class:`SrtConfig`; the
cluster config (``srtslurm.yaml``) is :class:`ClusterConfig`. This module walks
both and renders one Markdown table per dataclass, so the field-level reference
cannot drift from the code: both checked-in files are regenerated by
``srtctl schema-docs`` and CI fails when either is stale.

Two documents come out of one walk:

* ``schema-reference.md`` describes the 2.0 authoring surface only: the
  top-level ``engine:``, ``roles:``, and ``placement:`` vocabularies (from
  :mod:`srtctl.core.roles` and :mod:`srtctl.core.placement`) plus every
  dataclass field that is not a v1 spelling.
* ``legacy-v1.md`` is the single place the v1 layout is documented: the
  internal fields the 2.0 vocabularies normalize into, what each one became,
  and the classes that only exist for v1 recipes (``infra``, ``backend``,
  per-mode ``*_environment`` / ``<engine>_config``, ``mooncake_kv_store``).

Which fields are legacy is declared once in :data:`LEGACY_FIELDS`, derived from
the same constants the migrator uses (role names, engine config keys, placement
fields), and :mod:`tests.test_schema_docs` proves ``srtctl migrate`` removes
every one of them.

Descriptions come from two places, in priority order: an ``Attributes:`` block
in the class docstring (Google style), then the ``#`` comment block directly
above a field or the trailing comment on its line.
"""

